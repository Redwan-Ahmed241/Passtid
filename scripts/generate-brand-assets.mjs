/**
 * Rebuilds every logo-derived file from public/passtid-logo-exact.svg (the client's artwork,
 * never edited). Run it after the logo changes:  npm run brand:assets
 *
 *   public/logo.svg                      the wordmark, transparent and tightly cropped (header, footer)
 *   public/logo.png                      the same as a raster, for places that cannot use SVG
 *   public/icons/icon-192|512.png        app icons for the web manifest
 *   public/icons/icon-maskable-512.png   full-bleed icon for Android's adaptive shapes
 *   src/app/icon.svg                     the browser-tab icon
 *   src/app/apple-icon.png               iPhone / iPad home-screen icon
 *   src/app/favicon.ico                  16, 32 and 48 px frames for older browsers and crawlers
 *   src/lib/logo-data.ts                 the logo as a data URI, for the generated share image
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
function write(p, data) {
  const full = path.join(root, p);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, data);
  console.log("wrote", p, `(${Buffer.byteLength(data)} bytes)`);
}

const BLUE = "#3F6CB0";
const YELLOW = "#FECC02";

/* ---- the logo: same artwork, transparent background, cropped to its content ---- */
const original = read("public/passtid-logo-exact.svg");
const inner = original
  .replace(/^[\s\S]*?<svg[^>]*>/, "")
  .replace(/<\/svg>\s*$/, "")
  .replace(/<rect width="757" height="300" fill="#FFFFFF"\/>/, "");
// The content spans x 64.7..692.3 and y 52.5..207; this adds a small margin.
const logoSvg =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="58 46 641 168" width="641" height="168" role="img" aria-label="Passtid">` +
  inner +
  `</svg>\n`;
write("public/logo.svg", logoSvg);

const logoPng = await sharp(Buffer.from(logoSvg), { density: 600 }).resize({ width: 1282 }).png({ compressionLevel: 9 }).toBuffer();
write("public/logo.png", logoPng);

write(
  "src/lib/logo-data.ts",
  `// Generated by scripts/generate-brand-assets.mjs from public/logo.svg. Do not edit by hand.\n` +
    `export const LOGO_DATA_URI = "data:image/svg+xml;base64,${Buffer.from(logoSvg).toString("base64")}";\n` +
    `export const LOGO_ASPECT = 641 / 168;\n`,
);

/* ---- the mark: the check-mark "d" of the wordmark, on a blue square ---- */
const glyph = (heavy) =>
  heavy
    ? `<circle cx="641.8" cy="156" r="44" fill="none" stroke="${YELLOW}" stroke-width="20"/>` +
      `<rect x="662.3" y="72" width="30" height="133" fill="${YELLOW}"/>` +
      `<path d="M620.8 158 L632.8 170 L652.8 142" fill="none" stroke="${YELLOW}" stroke-width="14" stroke-linecap="round" stroke-linejoin="round"/>`
    : `<circle cx="641.8" cy="156" r="44" fill="none" stroke="${YELLOW}" stroke-width="13"/>` +
      `<rect x="670.3" y="72" width="22" height="133" fill="${YELLOW}"/>` +
      `<path d="M620.8 158 L632.8 170 L652.8 142" fill="none" stroke="${YELLOW}" stroke-width="9" stroke-linecap="round" stroke-linejoin="round"/>`;

/** A 512x512 square with the mark centred. `heavy` thickens the strokes so it survives at 16 px. */
function markSvg({ rx, scale, heavy }) {
  const cx = heavy ? 640.05 : 641.8;
  const cy = heavy ? 141 : 139.25;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">` +
    `<rect width="512" height="512" rx="${rx}" fill="${BLUE}"/>` +
    `<g transform="translate(256 256) scale(${scale}) translate(${-cx} ${-cy})">${glyph(heavy)}</g>` +
    `</svg>\n`
  );
}

const png = (svg, size) =>
  sharp(Buffer.from(svg), { density: 600 }).resize(size, size).png({ compressionLevel: 9 }).toBuffer();

const rounded = markSvg({ rx: 112, scale: 2.1, heavy: false });
const bleed = markSvg({ rx: 0, scale: 1.9, heavy: false }); // full-bleed; the mark stays inside the maskable safe zone
const tiny = (size) => markSvg({ rx: size <= 24 ? 96 : 112, scale: size <= 24 ? 2.5 : 2.3, heavy: true });

write("src/app/icon.svg", rounded);
write("src/app/apple-icon.png", await png(bleed, 180));
write("public/icons/icon-192.png", await png(rounded, 192));
write("public/icons/icon-512.png", await png(rounded, 512));
write("public/icons/icon-maskable-512.png", await png(bleed, 512));

/* ---- favicon.ico: PNG frames inside an ICO container ---- */
const sizes = [16, 32, 48];
const frames = await Promise.all(sizes.map((s) => png(tiny(s), s)));
const head = Buffer.alloc(6);
head.writeUInt16LE(0, 0); // reserved
head.writeUInt16LE(1, 2); // type: icon
head.writeUInt16LE(sizes.length, 4);
let offset = 6 + 16 * sizes.length;
const entries = sizes.map((s, i) => {
  const e = Buffer.alloc(16);
  e.writeUInt8(s, 0);
  e.writeUInt8(s, 1);
  e.writeUInt8(0, 2);
  e.writeUInt8(0, 3);
  e.writeUInt16LE(1, 4);
  e.writeUInt16LE(32, 6);
  e.writeUInt32LE(frames[i].length, 8);
  e.writeUInt32LE(offset, 12);
  offset += frames[i].length;
  return e;
});
write("src/app/favicon.ico", Buffer.concat([head, ...entries, ...frames]));
